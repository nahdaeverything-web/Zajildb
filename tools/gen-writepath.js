// tools/gen-writepath.js — regenerate docs/WRITEPATH-<version>.md from source.
//
// The v1.7 copy was assembled by hand and its line numbers drifted away from
// its own grep output within days. This reads the tree instead, so the document
// cannot disagree with the code it describes.
//
//   node tools/gen-writepath.js 1.8 > docs/WRITEPATH-v1.8.md

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const VERSION = process.argv[2] || '1.8';
const sh = (cmd) => { try { return execSync(cmd, { encoding: 'utf8' }).trim(); } catch { return ''; } };

function sources(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) sources(p, out);
    else if (name.endsWith('.js')) out.push(relative(ROOT, p));
  }
  return out;
}

// v1.9: js/db.js is a FACADE. It declares nothing, so reading it for
// `export function` finds an empty list. Follow the re-exports into js/db/
// instead, and report where each name is actually DEFINED — which is what a
// reader of this document needs anyway.
const db = readFileSync(join(ROOT, 'js/db.js'), 'utf8').split('\n');
const DB_MODULES = ['storage', 'oplog', 'records', 'io', 'sync'];

const facade = new Map();          // export name -> module basename
for (const m of readFileSync(join(ROOT, 'js/db.js'), 'utf8')
                  .matchAll(/export\s*\{([^}]*)\}\s*from\s*'\.\/db\/(\w+)\.js';/g)) {
  for (const raw of m[1].split(',')) {
    const name = raw.trim();
    if (name) facade.set(name, m[2]);
  }
}

const declared = new Map();        // export name -> { file, line, sig }
for (const mod of DB_MODULES) {
  const rel = `js/db/${mod}.js`;
  readFileSync(join(ROOT, rel), 'utf8').split('\n').forEach((line, i) => {
    let m = line.match(/^export (?:async )?function (\w+)\s*(\([^)]*\))?/);
    if (m) { declared.set(m[1], { file: rel, line: i + 1, sig: (m[2] || '()').trim() }); return; }
    m = line.match(/^export class (\w+)/);
    if (m) { declared.set(m[1], { file: rel, line: i + 1, sig: 'class' }); return; }
    m = line.match(/^export const (\w+)\s*=/);
    if (m) { declared.set(m[1], { file: rel, line: i + 1, sig: 'const' }); }
  });
}

const exports = [...facade.keys()].sort().map((name) => {
  const d = declared.get(name) || { file: `js/db/${facade.get(name)}.js`, line: 0, sig: '?' };
  return { name, sig: d.sig, file: d.file, line: d.line };
});

const missing = exports.filter((e) => !e.line);
if (missing.length) {
  // A name the facade re-exports but no module declares would mean the document
  // is describing an API that does not exist. Fail loudly rather than print it.
  console.error('gen-writepath: re-exported but not declared: ' + missing.map((e) => e.name).join(', '));
  process.exit(1);
}

const files = [...sources(join(ROOT, 'js')), ...sources(join(ROOT, 'tests')).filter((f) => f.endsWith('.js'))];

const out = [];
const w = (s = '') => out.push(s);

w(`# Zajil v${VERSION} — write path and call-site map`);
w();
w('**Generated by `node tools/gen-writepath.js` — do not hand-edit.**');
w('Every table below is derived from the source at generation time, so it cannot');
w('drift from the code the way a hand-written copy does.');
w();
w(`Repo: \`${sh('git rev-parse --short HEAD')}\` on \`${sh('git branch --show-current')}\``);
w();
w('`js/db.js` is a FACADE: ' + db.length + ' lines of comment and re-export, and');
w('nothing else. Every importer in the app depends on it and on nothing under');
w('`js/db/`. A guard in `tests/guards.test.js` pins the exact export set and');
w('asserts the file contains no logic.');
w();
w('| Module | Lines | Role |');
w('|---|---|---|');
for (const [mod, role] of [['storage', 'IndexedDB access, the in-memory mirror, change events'],
                           ['oplog', 'the op log and tombstones'],
                           ['records', 'the write boundary: birds, generic stores, media'],
                           ['io', 'export, import, sharing, backups'],
                           ['sync', 'accounts, push, pull, conflicts, status']]) {
  const lines = readFileSync(join(ROOT, `js/db/${mod}.js`), 'utf8').split('\n').length;
  w(`| \`js/db/${mod}.js\` | ${lines} | ${role} |`);
}
w();
w('Dependency direction, asserted by a guard: `storage <- oplog <- records <- io`,');
w('with `sync` above all of them. A cycle would hand one module a partly');
w('initialised namespace, and which one would depend on import order.');
w();
w('## 1. Everything js/db.js exports');
w();
w('```');
w('$ grep -c \'^\' js/db.js   # the facade');
w(String(db.length));
w('```');
w();
w(`${exports.length} names, each re-exported from the module that declares it.`);
w();
w('## 2. Call sites, per export');
w();
w('```');
w('$ grep -rn "\\b<SYMBOL>\\b" js/ tests/ tools/ --include=*.js | grep -v "^js/db.js:"');
w('```');
w();
w('| Export | Signature | Declared at | Called from |');
w('|---|---|---|---|');
for (const e of exports) {
  const hits = sh(`grep -rn "\\b${e.name}\\b" js/ tests/ tools/ --include=*.js`)
    .split('\n').filter((l) => l && !l.startsWith('js/db.js:') && !l.startsWith('js/db/'));
  const locs = [...new Set(hits.map((h) => h.split(':').slice(0, 2).join(':')))];
  const cell = locs.length ? locs.map((l) => `\`${l}\``).join('<br>') : '_(internal to the db layer)_';
  w(`| \`${e.name}\` | \`${e.sig.replace(/\|/g, '\\|').slice(0, 64)}\` | \`${e.file}:${e.line}\` | ${cell} |`);
}

w();
w('## 3. Direct IndexedDB access outside js/db.js');
w();
w('```');
w('$ grep -rnE "\\bidb(Put|Delete|Clear|Get|GetAll)\\b|indexedDB" js/ --include=*.js | grep -vE "^js/db(\\.js|/)"');
const raw = sh('grep -rnE "\\bidb(Put|Delete|Clear|Get|GetAll)\\b|indexedDB" js/ --include=*.js | grep -vE "^js/db(\\.js|/)"');
w(raw || '(no matches)');
w('```');
w();
w('Writes (`idbPut`/`idbDelete`/`idbClear`) outside `js/db/`: **none** — enforced');
w('by `tests/guards.test.js`, which since v1.9 exempts `js/db/` and NOT the');
w('facade: `js/db.js` provably contains zero writes, so it enjoys zero write');
w('privileges. Raw reads of `oplog`/`tombstones` are forbidden too:');
w('`idbGetAll` returns KEY order and the op-log key is a random uuid, so the raw');
w('result is unordered. Use `listOps()` / `getOpsSinceSeq()`.');
w();
w('## 4. Change events');
w();
w('```');
w('$ grep -rn "emitChange" js/db/ --include=*.js');
w(sh('grep -rn "emitChange" js/db/ --include=*.js'));
w();
w('$ grep -rn "onChange" js/ --include=*.js');
w(sh('grep -rn "onChange" js/ --include=*.js'));
w('```');
w();
w('## 5. The op log');
w();
w('```');
w('$ grep -rn "logOp\\|writeTombstone\\|clearTombstone\\|nextSeq" js/db/ --include=*.js');
w(sh('grep -rn "logOp\\|writeTombstone\\|clearTombstone\\|nextSeq" js/db/ --include=*.js'));
w('```');
w();
w('Every op: `{ opId, seq, deviceId, actorId, at, origin, store, op, recordId, changed, record }`.');
w('`origin` is `user` | `import` | `restore`. Conflict order comes from `seq`, a');
w('per-device monotonic counter — NOT from `updatedAt`, which `restoreBird`');
w('deliberately reinstates to an older value.');
w();
w('A deletion writes an op AND a tombstone sharing one `seq`: they are one');
w('logical operation. A restore deletes the tombstone.');
w();
w('## 6. Module inventory');
w();
w('| File | Lines |');
w('|---|---|');
for (const f of files.sort()) {
  w(`| \`${f}\` | ${readFileSync(join(ROOT, f), 'utf8').split('\n').length} |`);
}

console.log(out.join('\n'));
